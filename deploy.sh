#!/bin/bash

# 1. 自动进入你的博客文件夹
cd ~/blog || { echo "❌ 找不到 ~/blog 目录，请检查路径！"; exit 1; }

echo "========================================"
echo "🚀 赛博博客一键发布系统启动中..."
echo "========================================"

# 2. 展示当前有哪些文件被修改了
echo "🔍 正在检查本地文件变动..."
git status -s
echo "----------------------------------------"

# 3. 互动环节：让你输入今天更新了啥
# 如果直接按回车，脚本会自动帮你写上“日常更新 + 当前时间”
read -p "📝 请输入本次更新说明 (直接回车默认: '日常同步'): " msg
if [ -z "$msg" ]; then
    msg="日常同步 $(date '+%Y-%m-%d %H:%M:%S')"
fi

# 4. 自动执行 Git 三件套
echo "📦 1. 正在暂存修改..."
git add .

echo "💾 2. 正在本地打包提交..."
git commit -m "$msg"

echo "📡 3. 正在同步上云 (GitHub)..."
# 注意：这里默认你的分支是 main，如果你的是 master，可以把下面的 main 改成 master
if git push origin main; then
    echo "========================================"
    echo "🎉 部署成功！你的新成果已经稳稳上云！"
    echo "========================================"
else
    echo "❌ 推送失败，请检查手机网络或 GitHub 密钥配置！"
fi
